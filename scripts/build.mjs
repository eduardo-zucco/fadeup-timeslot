import { cp, mkdir, writeFile, readFile } from 'node:fs/promises';
import { loadAssets } from '../src/server/infrastructure/static-files.mjs';
await mkdir('dist/server', { recursive: true });
await mkdir('dist/.openai', { recursive: true });
await cp('src/server', 'dist/server/src/server', { recursive: true });
const assets = await loadAssets('public');
await writeFile('dist/server/assets.mjs', `export default ${JSON.stringify(assets)};\n`);
await writeFile('dist/server/index.js', "import { createWorker } from './src/server/worker.mjs';\nimport assets from './assets.mjs';\nexport default createWorker(assets);\n");
await writeFile('dist/.openai/hosting.json', await readFile('.openai/hosting.json'));
console.log('Worker gerado com módulos ESM: dist/server/index.js. Sem publicação.');
